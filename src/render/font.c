static const glyph *find_glyph(char c)
{
    size_t i;

    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');

    for (i = 0; i < sizeof(g_glyphs) / sizeof(g_glyphs[0]); i++)
        if (g_glyphs[i].c == c)
            return &g_glyphs[i];
    return NULL;
}

void psx_fb_rect(psx_framebuffer *fb, int x, int y, int w, int h, u16 colour)
{
    int px, py;

    if (!fb || !fb->px)
        return;

    for (py = y; py < y + h; py++) {
        if (py < 0 || py >= fb->height)
            continue;
        for (px = x; px < x + w; px++) {
            if (px < 0 || px >= fb->width)
                continue;
            fb->px[py * fb->width + px] = colour;
        }
    }
}

void psx_fb_rect_blend(psx_framebuffer *fb, int x, int y, int w, int h,
                       u16 colour, int alpha)
{
    int px, py;
    int cr = colour & 0x1F, cg = (colour >> 5) & 0x1F, cb = (colour >> 10) & 0x1F;

    if (!fb || !fb->px)
        return;
    if (alpha < 0)   alpha = 0;
    if (alpha > 255) alpha = 255;

    for (py = y; py < y + h; py++) {
        if (py < 0 || py >= fb->height)
            continue;
        for (px = x; px < x + w; px++) {
            u16 *p;
            int r, g, b;

            if (px < 0 || px >= fb->width)
                continue;

            p = &fb->px[py * fb->width + px];
            r = (*p) & 0x1F;
            g = ((*p) >> 5) & 0x1F;
            b = ((*p) >> 10) & 0x1F;

            r += ((cr - r) * alpha) / 255;
            g += ((cg - g) * alpha) / 255;
            b += ((cb - b) * alpha) / 255;

            *p = (u16)((b << 10) | (g << 5) | r);
        }
    }
}

int psx_fb_text_width(const char *text, int scale)
{
    int n = 0;

    if (!text)
        return 0;
    if (scale < 1)
        scale = 1;

    for (; *text; text++)
        n++;

    return n * (Q2_FONT_W + 1) * scale;
}

int psx_fb_text(psx_framebuffer *fb, int x, int y, const char *text,
                u16 colour, int scale)
{
    int cursor = x;

    if (!fb || !text)
        return 0;
    if (scale < 1)
        scale = 1;

    for (; *text; text++) {
        const glyph *g = find_glyph(*text);

        if (g) {
            int row, col;
            for (row = 0; row < Q2_FONT_H; row++) {
                for (col = 0; col < Q2_FONT_W; col++) {
                    if (!(g->row[row] & (1 << (Q2_FONT_W - 1 - col))))
                        continue;
                    psx_fb_rect(fb, cursor + col * scale, y + row * scale,
                                scale, scale, colour);
                }
            }
        }
        cursor += (Q2_FONT_W + 1) * scale;
    }

    return cursor - x;
}
